# Park+'s own vLLM server. No quota, no per-minute bucket, no daily cap — which is
# why it goes FIRST in the rotation and everything else becomes failover.
# MEASURED 2026-09-18 against the live endpoint:
#   - TTFT median 0.70s streaming (min 0.56, max 1.15). That is the number that
#     matters for voice: TTS starts on the first sentence, not on the last token.
#     Full completion is ~5.3s, which the caller never waits for.
#   - 65536 context, one model, served by vLLM.
#   - TLS validates. The curl that came with it used -k; that is not needed, and
#     disabling verification on a call carrying customer phone numbers is worse
#     than the inconvenience it saves. Verification stays ON here.

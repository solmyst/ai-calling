                # The nine bulbul:v3 female speakers, each confirmed to synthesise
                # on this key 2026-09-15 (anything outside this list is rejected):
                #   ritu, priya, neha, pooja, simran, kavya, ishita, shreya, roopa
                # "monika" is NOT one of them. Monika is the persona's name in the
                # prompt, and separately an ElevenLabs Voice Library voice
                # (zmh5xhBvMzqR4ZlXgcgL) which the API refuses on a free plan:
                # 402 paid_plan_required, "Free users cannot use library voices via
                # the API". So no value here brings that voice back.

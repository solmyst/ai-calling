# Groq says "Please try again in 617.142857ms"; Gemini says "Please retry in
# 54.441716995s". Same fact, two spellings, so match both.
_RETRY_AFTER_RE = re.compile(r"(?:try again|retry) in ([\d.]+)(ms|s)")


def _retry_after_seconds(error: Exception) -> float | None:
    """How long the provider said to wait, from the 429 body. None if it didn't say."""
    m = _RETRY_AFTER_RE.search(str(error))
    if not m:
        return None
    value = float(m.group(1))
    return value / 1000 if m.group(2) == "ms" else value


def _is_retryable(error: Exception) -> bool:
    """Would another endpoint plausibly answer this?

    Rate limits and outages, yes — that is the whole point of the rotation, and
    Gemini's "503 This model is currently experiencing high demand" is an outage
    that arrives looking nothing like a 429. A 400 or a 401 is our own request
    being wrong, and re-sending it to four more endpoints just spends four more
    seconds before failing anyway, so those still raise immediately.
    """
    if isinstance(error, (RateLimitError, APITimeoutError, APIConnectionError)):
        return True
    return isinstance(error, APIStatusError) and error.status_code >= 500


_NO_TOOL_SUPPORT_RE = re.compile(
    r"enable-auto-tool-choice|tool-call-parser|does not support tools", re.IGNORECASE)


def _is_dead_endpoint(error: Exception) -> bool:
    """Is this endpoint permanently unusable, rather than busy?

    A model that does not exist, a key that is not authorised: retrying it on the
    next turn is guaranteed to fail the same way. This is not hypothetical — the
    21:55 call died because "qwen/qwen3.6-27b" was in FALLBACK_MODELS and Groq
    404s it. Worse, the rotation had already pointed `self._settings.model` at it,
    so it stayed selected and every LATER turn 404'd too: one wrong string in a
    list took out the whole call rather than one turn.
    """
    # 402 is Bifrost's virtual-key budget cap:
    #   "Model-level budget exceeded (virtual key scope) ... 10.0045 >= 10.0000"
    # It is spent, not busy — no amount of waiting refills it, and the whole
    # point of holding Groq and Park+ behind Bifrost is that a spent key costs
    # nothing. Before this it was classified as neither retryable (429/5xx) nor
    # dead (401/403/404), so the rotation never moved: the endpoint stayed
    # selected and the bot answered NOTHING, on every turn, for the rest of the
    # process. Found on 2026-09-19 when the key hit its cap and all 17 eval
    # scenarios timed out at once, each waiting 60s for a reply that could never
    # come. On a live call that is the caller hearing silence until they hang up.
    if isinstance(error, APIStatusError) and error.status_code in (401, 402, 403, 404):
        return True
    # vLLM answers every tools request with 400 when the server was launched
    # without them: `"auto" tool choice requires --enable-auto-tool-choice and
    # --tool-call-parser to be set`. Every turn carries tools, so that endpoint
    # can never serve this bot — but it is a 400, and a bare 400 rule would also
    # retire an endpoint over one malformed request. Match the message, retire the
    # endpoint, and let the call continue on the next one instead of dying.
    return _NO_TOOL_SUPPORT_RE.search(str(error)) is not None


class Endpoint(NamedTuple):
    """One (provider, key, model) the rotation can fall back to."""

    api_key: str
    model: str
    base_url: str | None  # None = this service's own default, i.e. Groq
    provider: str


class FailoverLLMService(GroqLLMService):
    """LLM that survives a rate limit by moving to another key, model OR provider.

    Groq's free tier grants 8000 tokens/minute and this call spends ~3k of them
    every turn, so one bucket buys 2.3 turns a minute. A real Car Spa call — the
    caller asking why not their regular cleaner, what is included, how often,
    then giving five fields — runs 6 to 10. On 2026-09-14 the bot rotated its two
    keys and hit 429 on both on every single turn from 20:56 on; the caller heard
    nothing and the call was over before a booking could exist.

    Rotating (key, model) instead of key alone turns two budgets into eight. Gemini
    adds two more, and it is worth being honest about how small they are: 20
    requests per day per model on the free tier, so a few calls' worth in total.
    What it buys is not capacity, it is independence — Groq meters tokens per
    minute, Gemini meters requests per day, and a Groq outage is not a Gemini
    outage. It answers the turn where every Groq bucket is spent, which on
    2026-09-14 was the turn where the caller heard nothing at all.

    When every endpoint is spent, the provider's own 429 says how long to wait, and
    a wait under `max_wait` is taken rather than failing: a caller forgives one
    beat of silence, not a line that never comes.
    """

    def __init__(
        self,
        *,
        api_key: str,
        backup_api_keys: Sequence[str] = (),
        fallback_models: Sequence[str] = (),
        gemini_api_key: str | None = None,
        gemini_models: Sequence[str] = (),
        parkplus_url: str | None = None,
        parkplus_model: str = "",
        parkplus_api_key: str | None = None,
        bifrost_url: str | None = None,
        bifrost_models: Sequence[str] = (),
        max_history_tokens: int = 400,
        max_wait: float = 2.5,
        request_timeout: float = 10.0,
        **kwargs,
    ):
        super().__init__(api_key=api_key, **kwargs)
        # dict.fromkeys: a duplicated key is a duplicate BUDGET in the rotation but
        # not in reality, so it would just spend a turn re-hitting a spent quota.
        keys = list(dict.fromkeys(k for k in (api_key, *backup_api_keys) if k))
        primary = self._settings.model
        models = list(dict.fromkeys([primary, *fallback_models]))
        # Model-major: every key on the best model before any key on the second.
        # A weaker model is a real quality cost, so it is only reached once the
        # good one is spent everywhere.
        # Park+ runs its own LLM, so when it is configured it is the LAST stop:
        # Bifrost for speed, Park+ when Bifrost is spent, and nothing after that.
        # The free Groq and Gemini tiers are deliberately NOT behind it — they
        # are rate-limited, they are not ours, and the bot runs LLM_TOOLS=off
        # precisely because Park+'s vLLM has no tool support, so sliding onto a
        # different provider mid-call would quietly change what the bot can do
        # while a customer is on the line.
        #
        # Blank PARKPLUS_LLM_URL and the old Groq/Gemini chain comes back, which
        # is the escape hatch if Park+ is ever down: it is an env var an operator
        # already controls, not a new flag.
        if parkplus_url:
            self._endpoints = []
        else:
            self._endpoints = [Endpoint(k, m, None, "groq") for m in models for k in keys]
        if parkplus_url:
            self._endpoints.insert(
                0, Endpoint(parkplus_api_key or "not-needed", parkplus_model,
                            parkplus_url, "parkplus"))
        # Bifrost leads, and the reason is NOT time to first token — Park+ wins
        # that, 0.95s to 1.92s. It is reply LENGTH, which is what the caller
        # actually waits through. MEASURED 2026-09-18 on the same prompt:
        #     gemini/gemini-3.6-flash  131 chars -> ~10.7s of speech, full 2.46s
        #     ulkaa/Ornith             225 chars -> ~18.4s of speech, full 7.18s
        # At ~12 characters of Hindi per second that is nearly eight seconds per
        # turn, against a one-second penalty on the first token. Park+ stays
        # right behind it as the no-quota fallback.
        if bifrost_url:
            for model in reversed(list(bifrost_models)):
                self._endpoints.insert(0, Endpoint("not-needed", model, bifrost_url, "bifrost"))
        # Gemini last: it benchmarks as well as qwen3.8 on Hindi but answers in
        # 3-16s against Groq's sub-second, so it is what stands between the caller
        # and dead air, not what serves a normal turn.

        if gemini_api_key and not parkplus_url:
            self._endpoints += [
                Endpoint(gemini_api_key, m, GEMINI_BASE_URL, "gemini") for m in gemini_models
            ]
        self._index = 0
        # Whatever GroqLLMService pointed the client at, so rotating back off a
        # Gemini endpoint restores it instead of guessing the URL.
        self._default_base_url = self._client.base_url
        self._max_history_tokens = max_history_tokens
        self._max_wait = max_wait
        # The OpenAI SDK defaults to max_retries=2 and honours Groq's Retry-After
        # header, so it swallowed every 429 and slept through it instead: the
        # failover below never fired, and callers waited 13-29s in silence for a
        # reply. Surfacing the 429 immediately is what makes the second key useful.
        self._client.max_retries = 0
        # ...and it defaults to a 600s timeout, which on a phone call is not a
        # timeout at all. One measured Gemini request took over 60s. Past ~10s the
        # caller has already said "hello?" or hung up, so cut it off and let the
        # next endpoint answer.
        self._client.timeout = request_timeout
        # Point the client at endpoint 0. Without this the LIST says Park+ leads
        # while the CLIENT still holds whatever super().__init__ configured, so
        # the preferred endpoint is only ever reached after a failure wraps the
        # rotation around to it — i.e. never, on a healthy call.
        # Remember the Ornith-oriented frequency_penalty so Gemini can omit it
        # without losing the Park+/Groq preference when we fail over.
        self._frequency_penalty_pref = getattr(self._settings, "frequency_penalty", None)
        self._apply_endpoint(announce=False)

    def _trim_history(self, context) -> None:
        """Keep the newest turns that fit a TOKEN budget, not a message count.

        The system prompt plus tool schemas is ~2.5k tokens and the whole context
        is resent every turn, so on Groq's 7000 ITPM free tier an unbounded
        history is a death spiral: a five minute call had grown to 4669 prompt
        tokens/turn, which rate limited every remaining turn.

        Counting MESSAGES did not stop it. On the 2026-09-14 20:30 call the cap of
        16 was never reached and the prompt still climbed 2556 -> 3586 tokens,
        because a caller thinking out loud on an open mic produces single turns of
        400+ characters ("कॉन्टेक्स्ट में थोड़ी सी वो है, but हाँ वैसे सही डेट ही
        है..." ran 700). Sixteen of those is not 500 tokens, it is 1100, and the
        429s landed exactly on the turns that followed them. A budget is what the
        rate limit actually meters, so budget it directly.
        """
        messages = context.get_messages()
        # An assistant turn that was never speech does not belong in the history
        # either. On a live call qwen answered with a JSON error blob; the TTS
        # filter stops the caller HEARING it, but it stayed in the context as a
        # model turn and the six turns after it degraded ("आप रात को कब आना चाहते
        # हैं?" on a doorstep service). The filter sits downstream of the context
        # and cannot reach this, so it is dropped here, where the history lives.
        poisoned = [
            m
            for m in messages
            if _message_role(m) == "assistant"
            and is_machine_output(_message_text(m))
        ]
        if poisoned:
            logger.error(f"CONTEXT dropping {len(poisoned)} non-speech assistant turn(s)")
            messages = [m for m in messages if m not in poisoned]
            context.set_messages(messages)

        # Newest first until the budget runs out. The last two are kept whatever
        # they cost — the caller's current turn and what it answers are the one
        # thing the model cannot do without.
        kept: list = []
        spent = 0
        for message in reversed(messages):
            cost = _estimate_tokens(_message_text(message))
            if len(kept) >= 2 and spent + cost > self._max_history_tokens:
                break
            kept.append(message)
            spent += cost
        kept.reverse()

        # A tool result whose assistant tool_call was trimmed away is an orphan
        # and Groq rejects the request outright, so drop any leading one.
        while kept and _message_role(kept[0]) == "tool":
            kept.pop(0)
        if len(kept) < len(messages):
            logger.debug(f"CONTEXT {len(messages)} -> {len(kept)} msgs, ~{spent} tokens")
            context.set_messages(kept)

    async def get_chat_completions(self, context):
        self._trim_history(context)
        # Every (key, model) bucket once, then — only if they are all spent —
        # wait out the shortest of them. Sleeping first would add a beat of
        # silence to turns that another bucket could have answered instantly.
        shortest_wait: float | None = None
        for attempt in range(len(self._endpoints)):
            try:
                stream = await super().get_chat_completions(context)
                return self._log_finish_reason(stream, self._endpoints[self._index])
            except Exception as e:
                # A dead endpoint leaves the rotation entirely, so it cannot be
                # selected again for the rest of the call.
                if _is_dead_endpoint(e):
                    self._retire_endpoint(e)
                    if not self._endpoints:
                        raise
                    continue
                if not _is_retryable(e):
                    raise
                wait = _retry_after_seconds(e)
                if wait is not None:
                    shortest_wait = wait if shortest_wait is None else min(shortest_wait, wait)
                if attempt < len(self._endpoints) - 1:
                    self._next_endpoint(e)
                    continue

                if shortest_wait is not None and shortest_wait <= self._max_wait:
                    logger.warning(
                        f"All {len(self._endpoints)} LLM buckets spent — "
                        f"waiting {shortest_wait:.1f}s rather than going silent"
                    )
                    await asyncio.sleep(shortest_wait)
                    self._next_endpoint(e)
                    return await super().get_chat_completions(context)
                raise

    async def _log_finish_reason(self, stream, endpoint: "Endpoint"):
        """Pass the stream through unchanged, but log HOW it ended.

        RCA, 2026-09-21: replies keep cutting off mid-sentence regardless of
        which STT is active (Sarvam, then AssemblyAI) — so the cause is not on
        the caller's side of the pipeline. The one thing both STT swaps left
        untouched is max_completion_tokens=280 (line ~1503). If the model hits
        that cap, the API returns finish_reason="length" and the completion IS
        the truncated text, not something TTS or turn-taking cut short. This
        line makes that visible instead of guessed.
        """
        finish_reason = None
        completion_tokens = None
        reasoning_tokens = None
        async for chunk in stream:
            choice = chunk.choices[0] if chunk.choices else None
            if choice and choice.finish_reason:
                finish_reason = choice.finish_reason
            usage = getattr(chunk, "usage", None)
            if usage:
                completion_tokens = usage.completion_tokens
                # RCA, 2026-09-22: wall-clock LATENCY alone couldn't tell us
                # whether reasoning={"effort": "low"} (bot.py's is_gemini
                # branch) is actually reducing Gemini's thinking, or silently
                # no-op'ing the same way the flat reasoning_effort field did
                # before it — a live call after that fix showed LATENCY
                # unchanged (2.6-3.75s) with no way to tell why. This is the
                # direct measurement instead of another guess: OpenAI-style
                # reasoning APIs report spend here, at
                # usage.completion_tokens_details.reasoning_tokens.
                details = getattr(usage, "completion_tokens_details", None)
                if details is not None:
                    reasoning_tokens = getattr(details, "reasoning_tokens", None)
            yield chunk
        if finish_reason == "length":
            logger.warning(
                f"LLM TRUNCATED | {endpoint.provider}:{endpoint.model} hit "
                f"max_completion_tokens ({completion_tokens} tokens) — the reply "
                f"was cut off by the token cap, not by STT/turn-taking"
            )
        elif finish_reason:
            logger.info(f"LLM finish_reason={finish_reason} | {endpoint.provider}:{endpoint.model}")
        if reasoning_tokens is not None:
            logger.info(
                f"LLM REASONING | {endpoint.provider}:{endpoint.model} spent "
                f"{reasoning_tokens} reasoning tokens of {completion_tokens} total"
            )

    def _retire_endpoint(self, error: Exception) -> None:
        """Drop the current endpoint for good and point the client at the next."""
        dead = self._endpoints.pop(self._index)
        logger.error(
            f"DROPPED {dead.provider}:{dead.model} from the rotation for this call "
            f"— {type(error).__name__}: {str(error)[:120]}"
        )
        if not self._endpoints:
            return
        self._index %= len(self._endpoints)
        self._apply_endpoint(error)

    def _next_endpoint(self, error: Exception | None = None) -> None:
        self._index = (self._index + 1) % len(self._endpoints)
        self._apply_endpoint(error)

    def _apply_endpoint(self, error: Exception | None = None, announce: bool = True) -> None:
        endpoint = self._endpoints[self._index]
        self._client.api_key = endpoint.api_key
        # base_url is what makes a Gemini endpoint reachable from a Groq service.
        # httpx wants a trailing slash or it drops the last path segment, which
        # turns /v1beta/openai/chat/completions into /v1beta/chat/completions.
        self._client.base_url = (
            f"{endpoint.base_url}/" if endpoint.base_url else self._default_base_url
        )
        self._settings.model = endpoint.model
        is_gemini = (
            endpoint.provider in ("bifrost", "gemini") or "gemini" in endpoint.model.lower()
        )
        extra = dict(self._settings.extra)
        if is_gemini:
            # LATENCY + LEAK bug, 2026-09-22: this branch used to send the flat
            # OpenAI-style "reasoning_effort" field, same as the Groq-native
            # branch below. Bifrost's own docs (docs.getbifrost.ai/providers/
            # reasoning) say that flat field is NOT accepted for Gemini — only
            # the nested {"reasoning": {"effort"/"max_tokens": ...}} object is.
            # It never errored, so this went unnoticed: Gemini has been running
            # at its OWN default thinking level this whole time, not "low" —
            # the real cause of the 2s+ latency AND of reasoning text leaking
            # into what gets spoken (Bifrost's docs: include_thoughts is on by
            # default whenever reasoning is active, and only goes false when
            # max_tokens=0). Dropped the flat field; see extra_body below.
            extra.pop("reasoning_effort", None)
        else:
            extra["reasoning_effort"] = _reasoning_effort(endpoint.model)
        if endpoint.provider == "parkplus":
            # Belt and braces. reasoning_effort alone silenced the thinking in
            # testing, but the failure it prevents is the bot reading its own
            # English reasoning to a Hindi caller, so send the vLLM switch too.
            #
            # It MUST go inside extra_body. base_llm does params.update(extra)
            # and then create(**params), and the OpenAI SDK rejects any kwarg it
            # does not define: passing it at the top level raised
            # "AsyncCompletions.create() got an unexpected keyword argument
            # 'chat_template_kwargs'" on every single turn of the 16:31 call, and
            # a local TypeError is not an APIStatusError, so the failover could
            # not see it and the bot said nothing at all.
            extra["extra_body"] = {"chat_template_kwargs": {"enable_thinking": False}}
            # Ornith accepts frequency_penalty; restore it when we land here.
            if getattr(self, "_frequency_penalty_pref", None) is not None:
                self._settings.frequency_penalty = self._frequency_penalty_pref
        elif is_gemini:
            # CHANGED 2026-09-22, third pass — measured directly against
            # Bifrost, not guessed. Curled bifrost.parkplus.io with the exact
            # same request shape bot.py sends, for gemini-3.6-flash, on a
            # trivial one-word question ("capital of India"):
            #   effort=low     -> 264 of 267 completion tokens on reasoning,
            #                      4.7s server-side latency
            #   effort=high    -> 476 of 479 tokens on reasoning, 6.3s
            #   effort=minimal -> 0 reasoning tokens, 2 completion tokens,
            #                      2.0s. A realistic system+user prompt at
            #                      minimal: 37 tokens, clean Hindi content,
            #                      no leaked reasoning text, no reasoning
            #                      tokens spent, 2.86s.
            # "low" was not a meaningful reduction for this model at all —
            # Bifrost's mapping table says "low"/"minimal" both go to
            # thinking_level LOW, but the live numbers above say otherwise;
            # trust the measurement over the docs. "minimal" is the one that
            # actually removes the reasoning pass.
            extra["extra_body"] = {"reasoning": {"effort": "minimal"}}
            from openai import NOT_GIVEN
            self._settings.frequency_penalty = NOT_GIVEN
            self._settings.presence_penalty = NOT_GIVEN
        else:
            # Plain Groq-native models (qwen, gpt-oss). Gemini/Bifrost 400s with
            # "Penalty is not enabled for this model" if frequency_penalty /
            # presence_penalty is sent — caught live 17:45 — but that's the
            # is_gemini branch above now, not this one.
            extra.pop("extra_body", None)
            if getattr(self, "_frequency_penalty_pref", None) is not None:
                self._settings.frequency_penalty = self._frequency_penalty_pref
        self._settings.extra = extra
        if not announce:
            return
        why = type(error).__name__ if error else "rotating"
        logger.warning(
            f"{why} — trying {endpoint.provider}:{endpoint.model} "
            f"on key #{self._keys.index(endpoint.api_key) + 1}"
        )

    @property
    def _keys(self) -> list[str]:
        """Distinct keys, in rotation order — for logging which one is in play."""
        return list(dict.fromkeys(e.api_key for e in self._endpoints))


class PriceGuardFilter(BaseTextFilter):
    """Runs the deterministic price check on every sentence before it is spoken.

    Sits in the TTS service's text_filters, so it catches the text on its way to
    the voice regardless of which model produced it or what the prompt said.
    """

    # Every list PriceGuard appends to, and what to say when it grows. Was six
    # positional entries in a tuple indexed by hand; each new guard meant a new
    # magic index, so it is a table now — adding a guard is one row.
    # WARNING is for counters that only observe (nothing was changed); ERROR is
    # for text that was actually rewritten or dropped before the caller heard it.
    # Kept only as the car spa's table; a guard that declares its own COUNTERS
    # (see domains/insurance/guard.py) overrides it, because which rules exist
    # is a property of the domain, not of this filter.
    _COUNTERS = (
        ("blocked", logger.error, "blocked invented price(s)"),
        ("odd_times", logger.warning, "saw a non-standard slot time"),
        ("false_confirmations", logger.error, "rewrote a booking claimed as done"),
        ("romanised", logger.warning, "SCRIPT DRIFT, romanised (not rewritten)"),
        ("labels", logger.error, "stripped a leaked speaker label"),
        ("availability_claims", logger.error, "rewrote a slot/area availability claim"),
        ("damage_promises", logger.error, "rewrote a damage/liability promise"),
        ("body_type_asks", logger.error, "rewrote a hatchback/sedan/SUV question"),
        ("self_ai", logger.error, "rewrote the bot announcing it is an AI"),
        ("machine_output", logger.error, "DROPPED non-speech output"),
        ("priced_before_car", logger.error, "blocked a price before the caller named a car"),
        ("self_narration", logger.error, "DROPPED the model thinking out loud"),
    )

    def __init__(self, guard=None):
        self._guard = guard or PriceGuard()
        counters = getattr(self._guard, "COUNTERS", None)
        if counters:
            levels = {"error": logger.error, "warning": logger.warning,
                      "info": logger.info}
            self._counters = tuple((n, levels[lvl], what) for n, lvl, what in counters)
        else:
            self._counters = self._COUNTERS

    async def filter(self, text: str) -> str:
        # The sentence splitter can emit a chunk that is pure punctuation (a lone
        # "." after "gunga.."), which Sarvam 400s on and then drops the WebSocket,
        # costing a reconnect mid-call. TTS skips a filter that returns empty.
        if not _SPEAKABLE_RE.search(text):
            return ""

        g = self._guard
        before = {name: len(getattr(g, name)) for name, _, _ in self._counters}
        cleaned = g.check(text)
        for name, log, what in self._counters:
            seen = getattr(g, name)
            if len(seen) > before[name]:
                log(f"GUARDRAIL {what} {seen[before[name]:]} in: {text!r}")
        return cleaned

    async def handle_interruption(self):
        pass

    async def reset_interruption(self):
        pass



class GuardFilter(BaseTextFilter):
    """Runs the active domain's guard on every sentence before it is spoken.

    Sits in the TTS service's text_filters, so it catches the text on its way to
    the voice regardless of which model produced it or what the prompt said.
    """

    def __init__(self, guard):
        self._guard = guard
        # Which rules exist is a property of the domain, so each guard declares
        # its own COUNTERS: (list attribute, log level, what to say when it grows).
        levels = {"error": logger.error, "warning": logger.warning, "info": logger.info}
        self._counters = tuple(
            (n, levels[lvl], what) for n, lvl, what in guard.COUNTERS
        )

    async def filter(self, text: str) -> str:
        # The sentence splitter can emit a chunk that is pure punctuation (a lone
        # "." after "gunga.."), which Sarvam 400s on and then drops the WebSocket,
        # costing a reconnect mid-call. TTS skips a filter that returns empty.
        if not _SPEAKABLE_RE.search(text):
            return ""
        # Fillers and the bot's own fixed lines are not model output. Run
        # through the guard, the hum "उम्म," was taken for a mismatch reply and
        # replaced with the forward line (live call 2026-09-23, three bogus
        # GUARDRAIL lines including an ERROR).
        if text.strip() in _bot_owned_lines():
            return text

        g = self._guard
        before = {name: len(getattr(g, name)) for name, _, _ in self._counters}
        cleaned = g.check(text)
        for name, log, what in self._counters:
            seen = getattr(g, name)
            if len(seen) > before[name]:
                log(f"GUARDRAIL {what} {seen[before[name]:]} in: {text!r}")
        return cleaned

    async def handle_interruption(self):
        pass

    async def reset_interruption(self):
        pass


# How many times a caller has to ask before the call is really handed over.
# The counter lives here, not in the prompt, because the model cannot count its
# own turns: on a live call it called the handover tool on the caller's FIRST
# "owner का number दो" and then spent four turns promising a colleague who was
# never coming. The model still calls the tool whenever it thinks handover — the
# tool decides whether that is what actually happens.
ESCALATE_AFTER_ASKS = 3

# What to do instead, per ask. Indexed by ask number; the last entry is reached
# only if ESCALATE_AFTER_ASKS is raised past the list.
_DEFLECTIONS = [
    "Do NOT hand over. Apologise once in half a sentence, then solve it yourself: "
    "answer what they actually asked, in one or two sentences, and ask the one "
    "question that moves the call on.",
    "Still do NOT hand over. Say plainly what you CAN do right now — the next step "
    "for them, or a callback at a time they choose — and offer that. You have no "
    "colleague's phone number to give out, so never promise one.",
]


def _make_escalate_tool():
    """Build a per-session handover tool. The closure is the call's ask counter."""
    asks = 0

    async def escalate_to_human(params: FunctionCallParams, reason: str):
        """Ask to hand the call to a human agent. Call this EVERY time the customer
        asks for a person, a manager or an owner's number, is angry, wants to
        cancel or refund, or you failed to understand twice. Follow its reply
        exactly — it does NOT always hand over.

        Args:
            reason: Short note on why, for the human picking it up.
        """
        nonlocal asks
        asks += 1
        if asks < ESCALATE_AFTER_ASKS:
            logger.info(
                f"Escalation ask {asks}/{ESCALATE_AFTER_ASKS} held back: {reason}"
            )
            await params.result_callback(
                {
                    "status": "handle_it_yourself",
                    "asks_so_far": asks,
                    "say": _DEFLECTIONS[min(asks, len(_DEFLECTIONS)) - 1],
                }
            )
            return
        logger.warning(f"ESCALATION (ask {asks}): {reason}")
        await params.result_callback(
            {
                "status": "escalating",
                "say": "Tell the customer you are putting them through to a colleague. "
                "One short line, then stop — do not start a new question.",
            }
        )

    return escalate_to_human


async def end_call(params: FunctionCallParams):
    """End the call once the goodbye is said.

    Call this after thanking the customer and saying goodbye — when they refuse
    KYC, when the ask is done, or when they clearly want to hang up. Speak the
    goodbye first; this tool hangs up after queued audio finishes.
    """
    logger.info("end_call tool — hanging up after queued audio")
    await params.result_callback({"success": True})
    await params.llm.push_frame(EndWorkerFrame(reason="end_call_tool"))


def _call_limit_secs(env_name: str, default: float) -> float | None:
    """Parse a call-safety timeout from env. Blank = default; 0 or less = off."""
    raw = os.getenv(env_name)
    if raw is None or raw.strip() == "":
        return default
    try:
        value = float(raw)
    except ValueError:
        logger.warning(f"{env_name}={raw!r} is not a number — using {default}")
        return default
    return value if value > 0 else None



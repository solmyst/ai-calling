async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """Run the voice bot for this session.

    Args:
        transport: The transport for this session, built by ``create_transport``
            (or by hand for the dial-out/SIP production flows).
        runner_args: Runner session arguments. Carries the request ``body``
            (e.g. dial-out settings, SIP call details) and ``session_id``; the
            standard web/telephony pipelines don't need it.
    """
    _setup_logging()
    logger.info("Starting bot")

    # What we know about the person we just dialled, prefetched by the dialer and
    # handed over as the runner body (`--runner-body`, or `runner_body:` in an
    # eval manifest). One fixed query before the call — never a database
    # connection during it, and never free-form SQL the model composes while
    # somebody listens to silence.
    #
    # No card is a fully supported state. If the prefetch fails, times out, or
    # the dialer has not been updated yet, the bot falls back to exactly the
    # generic call it ran before any of this existed.
    card = build_call_card(getattr(runner_args, "body", None))
    # Dev convenience, 2026-09-22: the browser test UI sends a fixed body with
    # no room for a call card, so there was no way to test against a REAL
    # case locally short of hand-crafting a runner body. TEST_CALL_CARD is a
    # raw JSON object, tried only when the request itself carried no card —
    # a real dialer body always wins. Unset in .env.example on purpose; this
    # is for a specific local test, not something to leave on.
    if not card and os.getenv("TEST_CALL_CARD"):
        try:
            card = build_call_card(json.loads(os.environ["TEST_CALL_CARD"]))
        except (json.JSONDecodeError, TypeError) as e:
            logger.warning(f"TEST_CALL_CARD is not valid JSON, ignoring: {e}")
    if card:
        # Names and registration numbers are customer data; call.log gets the
        # shape of the card, not its contents.
        logger.info(
            f"CALL CARD goal={card['goal']} insurer={card.get('insurer') or '?'} "
            f"kyc={card.get('kyc_status') or '?'} "
            f"fields={sorted(k for k in card if k != 'goal')}"
        )
    else:
        logger.info("No call card — running the generic KYC call")

    groq_key = os.getenv("GROQ_API_KEY")
    # STT and the LLM can run on separate Groq keys so one key isn't carrying both
    # call legs. Note this only spreads real load if the keys belong to DIFFERENT
    # Groq accounts — Groq meters rate limits per account, not per key.
    groq_stt_key = os.getenv("GROQ_STT_API_KEY") or groq_key
    stt_language = os.getenv("WHISPER_LANGUAGE") or "hi"

    # Speech-to-Text, in order of preference.
    #
    # AssemblyAI streams over a WebSocket, so partial transcripts arrive while the
    # caller is still talking — better turn-taking and interruption than Groq, which
    # is batch (nothing comes back until the caller stops, then ~0.9s).
    #
    # Groq whisper-large-v3 is the accuracy benchmark here: on Hinglish clips it got
    # "kal subah aath baje ka slot chahiye" exactly, resolving "aath baje" to "8 बजे",
    # where local base produced "Tomorrow morning we have to go to bed". It costs
    # ~0.9s/clip vs ~0.5s for -turbo, worth it since a misheard slot corrupts the
    # booking. language="hi" beats auto-detect, which flipped language per utterance.
    # Park+'s own ASR first, for the same reason as the LLM: Park+ runs it, so
    # there is no per-minute bill and no third-party quota. Set PARKPLUS_STT_URL
    # to use it; unset, nothing changes and AssemblyAI stays.
    #
    # Turned OFF again on 2026-09-21. It has no noise suppression, no turn model
    # and no keyterms, and the 12:51 call shows what that costs: the other people
    # in the room were transcribed as the caller, in romanised Hindi, with no way
    # to tune it. AssemblyAI's U3 Pro below has voice_focus and its own turn
    # detection, which is what those calls actually needed.
    #
    # Its transcripts are ROMANISED Hindi ("Haan ji meri creta hai"), not
    # Devanagari. That is fine for the LLM and for the car gate, which matches
    # "creta" case-insensitively — but it is why NoiseGate cannot lean on
    # "has Devanagari" to mean "real speech" once this is on.
    parkplus_stt_url = os.getenv("PARKPLUS_STT_URL")
    assemblyai_key = os.getenv("ASSEMBLYAI_API_KEY")
    # A/B trial, 2026-09-21. SARVAM_STT=1 tries Sarvam's realtime STT instead of
    # AssemblyAI — same vendor as TTS, so no new key, and it has a real Pipecat
    # integration (SarvamRealtimeSTTService), unlike Park+'s hand-rolled one.
    #
    # What it does NOT have, checked against the source before wiring this:
    #   - Speculative/eager inference. Same gap as AssemblyAI and Park+ — only
    #     Cartesia's STT implements that mixin in this Pipecat build. Switching
    #     here does not buy "start the LLM before the caller finishes talking".
    #   - A keyterms list. Only a free-text `prompt`, left unset below for the
    #     same reason AssemblyAI's is: a custom prompt REPLACES the vendor's own
    #     tuned default, and that trade should be measured, not assumed.
    #   - A named noise-suppression feature (AssemblyAI's voice_focus). Only a
    #     general VAD `threshold` — confirmed live (18:47 call) that Sarvam's
    #     own default of 0.3 is too permissive for the same noisy rooms
    #     voice_focus was tuned for; raised below, see the comment on
    #     `threshold=` for the evidence.

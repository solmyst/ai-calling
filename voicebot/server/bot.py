    #
    # Sarvam is first because it is the only option here with a genuinely Indian
    # Hindi voice. ElevenLabs' free tier cannot use Voice Library voices via the
    # API at all — adding "Monika Sogam" to the library still returns 402
    # paid_plan_required, and the account reports can_use_professional_voice_cloning
    # false — so on free tier it can only speak Hinglish in a US/UK accent.
    # ONE guard for the whole call, shared by the TTS filter (what the bot says)
    # and the observer (what the caller says). Two instances would mean the filter
    # never learns that a car was named, and every price would be blocked.

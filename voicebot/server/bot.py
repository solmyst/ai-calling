def _message_role(message) -> str | None:
    """Role of a context message, whether it is a dict or an LLMSpecificMessage."""
    inner = getattr(message, "message", message)
    return inner.get("role") if isinstance(inner, dict) else None


def _message_text(message) -> str:
    """Text of a context message, whether it is a dict or an LLMSpecificMessage."""
    inner = getattr(message, "message", message)
    content = inner.get("content") if isinstance(inner, dict) else None
    return content if isinstance(content, str) else ""


def _estimate_tokens(text: str) -> int:
    """Rough token cost of a message, for the history budget.

    3.2 chars/token is the ratio measured against Groq's own prompt_tokens on this
    Devanagari/English mix (scratchpad/t_tokens.py). The 4 is the per-message
    role/scaffolding overhead, which matters when the history is many short turns.
    An estimate is fine here — it decides what to drop, never what to bill.
    """
    return int(len(text) / 3.2) + 4


def _reasoning_effort(model: str) -> str:
    """The lowest reasoning setting each model family will actually accept.

    LLM_REASONING_EFFORT env overrides the per-family default when set
    (low | medium | high | none). Use it to force a value without editing code.

    Three families now, and none of them agree:
      - Groq's gpt-oss rejects "none" outright — `400: reasoning_effort must be
        one of low, medium, or high` — minimum is "low".
      - qwen accepts "none" and means it.
      - Gemini 3 (gemini-3.5-flash, gemini-3.6-flash — both bare and Bifrost's
        "gemini/"-namespaced form) does NOT accept "none" as a real off switch.
        Google's own docs: "Reasoning cannot be turned off for Gemini 2.5 Pro or
        3 models." We were sending "none" anyway, and it was not a no-op — it
        was invisibly the WRONG value being silently reinterpreted, most likely
        as the model's default thinking level ("medium" for 3.x flash). Caught
        in our own logs before this was diagnosed: guardrails.py's
        _SELF_NARRATION_RE was written specifically because gemini-3.6-flash
        leaked its hidden reasoning as spoken English — "I need to investigate
        this further. Let me check the details." — WITH reasoning_effort
        already set to "none" (guardrails.py:165). That is direct evidence the
        model was still doing real reasoning work despite the setting, which is
        also the leading suspect for why Gemini's measured full-turn latency
        (2.46s) sits so far above Park+'s (0.95s), where thinking is actually
        off via the vLLM chat_template_kwargs switch.

        "low" is the lowest value Google's OpenAI-compatibility docs confirm as
        both valid and fastest for Gemini 3 flash. It is not zero — reasoning
        cannot be zero on this model family — but it is real self-consistent
        input rather than a value the API has to guess how to handle.
    """
    forced = (os.getenv("LLM_REASONING_EFFORT") or "").strip().lower()
    if forced in ("none", "low", "medium", "high"):
        # Gemini / gpt-oss reject "none" — bump to low so a global env of "none"
        # cannot 400 the live call.
        if forced == "none" and (
            "gemini" in model.lower() or model.startswith("openai/gpt-oss")
        ):
            return "low"
        return forced
    if model.startswith("openai/gpt-oss"):
        return "low"
    if "gemini" in model.lower():
        return "low"
    return "none"


def _stt_keyterms() -> list[str]:
    """Domain vocabulary to bias the transcriber toward.

    The proper nouns are where a Hinglish call actually breaks. In one real car
    spa call "car spa" came back as "कारिस पर" and "Royal Enfield" as "रॉयल
    फील्ड" — the bot then reasoned correctly about the wrong words. For a KYC
    call it is the insurer names and the field labels the customer reads off
    their own screen.

    The list lives in the DOMAIN's context.json, not here. It used to be built
    from car-spa price tiers inline, which meant this function raised
    KeyError: 'pricing' under DOMAIN=insurance — masked only because the Park+
    STT branch was selected and never called it. Switching STT would have killed
    the bot at startup.
    """
    ctx = json.loads(CONTEXT_FILE.read_text())
    return sorted(ctx.get("stt_keyterms", []))


def _stt_prompt() -> str | None:
    """A plain description of what this recording IS — OFF unless asked for.

    Keyterms bias individual words; this gives the transcriber the situation.
    AssemblyAI publishes 21% lower word error rate and 49% fewer name-entity
    errors for a detailed prompt, which reads like the biggest accuracy lever
    available — and is why the prompt in context.json exists.

    It is off by default anyway, because the SDK says so out loud the moment you
    set one:

        "Prompting is a beta feature. We recommend testing with no prompt first,
         as this will use our optimized default prompt for voice agents. Bad
         prompts may lead to bad results."

    So "no prompt" does not mean no context — it means AssemblyAI's own
    voice-agent prompt, tuned on far more calls than this one bot. The published
    21% is against nothing at all, not against that default, and a custom prompt
    REPLACES it. Handing that away for an unmeasured 48 words is a bad trade
    made blind.

    ASSEMBLYAI_CONTEXT_PROMPT=1 sends ours instead, for when there is a live
    call to A/B it against. Until then the vendor's default wins on evidence.
    """
    if (os.getenv("ASSEMBLYAI_CONTEXT_PROMPT") or "").lower() not in ("1", "on", "true"):
        return None
    ctx = json.loads(CONTEXT_FILE.read_text())
    return ctx.get("stt_prompt") or None


def _extra_groq_keys() -> list[str]:
    """Every Groq key in the environment besides GROQ_API_KEY, for the failover.

    Quotas are per key (measured, scratchpad/t_keys.py), so this is the one free
    lever on the free tier that costs no prompt quality: each extra key is another
    8000 tokens/minute, and ~3k/turn means roughly 2.6 more turns a minute.
    Anything named GROQ_API_KEY_2, _3, ... is picked up with no code change.
    """
    return [
        v
        for k, v in sorted(os.environ.items())
        if v and k.startswith("GROQ_") and "API_KEY" in k and k != "GROQ_API_KEY"
    ]



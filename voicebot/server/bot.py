_LOGGING_READY = False


def _setup_logging() -> None:
    """One readable feed of the call, instead of Pipecat's full DEBUG firehose.

    At DEBUG, Pipecat prints the entire 2000-token system prompt on every connect
    and the entire message context on every turn. A five minute call was 5000+
    lines, and the three lines that mattered — what the caller said, what Monika
    said, what broke — were buried in ICE candidates. INFO drops all of that;
    CallLogObserver puts the conversation back in, one line per turn.

    LOG_LEVEL=DEBUG brings the firehose back when a frame-level bug needs it.
    The same feed is written to call.log so a whole call can be attached as a
    file rather than pasted.

    Called from run_bot, not from __main__, because pipecat.runner.run.main()
    does its own logger.remove() and re-adds stderr at DEBUG — configuring
    before it just gets wiped. Guarded because run_bot runs once per call and
    a second logger.add(CALL_LOG) would write every line to the file twice.
    """
    global _LOGGING_READY
    if _LOGGING_READY:
        return
    _LOGGING_READY = True
    level = os.getenv("LOG_LEVEL") or "INFO"
    logger.remove()
    fmt = "{time:HH:mm:ss.SSS} | {level: <7} | {message}"
    logger.add(sys.stderr, level=level, format=fmt)
    logger.add(CALL_LOG, level=level, format=fmt, rotation="5 MB", retention=3)
    # Breakage alerts to Slack (errors, and a call dropped by a dead service).
    # enqueue=True: the sink runs on loguru's own thread, never in the call loop.
    if slack.enabled():
        logger.add(slack.alert_sink, level="WARNING", filter=slack.alert_filter,
                   format="{message}", enqueue=True)


# Silence is not silent on a phone line, and ASR models answer it with whatever
# they heard most in training. MEASURED from call.log: on Hindi calls where the
# caller said nothing, AssemblyAI produced "Thank you.", "Thank", "Cool." and
# "So yeah." — English, in a Devanagari conversation. The bot then answered them,
# which is why a caller said "ये बाहर की वो नोइज़ ले लेता है".
#
# Only phrases with BOTH properties are listed: they are documented ASR
# silence-hallucinations, and a Gurugram caller booking a car wash would not say
# them alone as a turn. "Hello", "bolo", "okay", "yes" and "bye" are NOT here on
# purpose — "Bolo." appears in the same log and is a real caller saying बोलो in
# Latin script. Dropping short Latin text as a class would eat real speech.
#
# That last point got sharper with PARKPLUS_STT_URL: Park+'s ASR returns
# ROMANISED Hindi, so "Haan ji meri creta hai" is Latin-only too. The Devanagari
# check below is now an early exit for AssemblyAI's output, not the main defence
# — this exact phrase list is. Keep it exact-match and keep it short.
_NOISE_TRANSCRIPTS = frozenset({
    "thank", "thank you", "thanks", "thanks for watching", "thank you very much",
    "cool", "so yeah", "you", "uh", "um", "hmm", "mm", "mhm", "ah",
    # 15:53 browser call — laptop mic + room bleed hallucinated as English
    # turns ("Marine Toy.") and earned full KYC replies. Exact-match only.
    "marine toy", "marine", "toy", "subtitle", "subtitles", "music",
    "applause", "laughing", "laughter",
})

# Devanagari backchannels: the noise a caller makes while still thinking. In the
# 14:55 call a bare "ओह" arrived two seconds after a real question and earned a
# whole second reply, so the bot answered twice in a row with nobody having
# asked anything.
#
# This set is deliberately tiny and holds NO answers. "हाँ", "नहीं", "ठीक है"
# and "हो गया" are single words too, and every one of them is a real reply to
# "page खुल गया?" — dropping those would be far worse than the duplicate turn
# this prevents. Only sounds that carry nothing at all belong here.
_HINDI_BACKCHANNELS = frozenset({
    "ओह", "ओ", "हम्म", "हम", "हूँ", "हूं", "उम्म", "अम्म", "अरे", "अच्छा",
    "अच्छा अच्छा", "हम्म हम्म", "ओह अच्छा",
})

# The same sounds as Park+'s ASR spells them. It returns ROMANISED Hindi
# ("Haan ji meri creta hai"), not Devanagari, so with PARKPLUS_STT_URL set the
# Devanagari set above never matches a thing and every one of these earns a
# full reply — which is the duplicate-answer bug the set was added to stop.
#
# Same discipline as above: NO answers. "haan", "nahi", "theek hai", "ho gaya"
# and "ok" are all one-word replies to "page khul gaya?", and dropping one
# leaves the bot waiting for something the caller already said. Bare "are" is
# left out too, because it is an English word.
_ROMAN_BACKCHANNELS = frozenset({
    "oh", "ohh", "ooh", "achha", "acha", "accha", "achcha", "arre", "arey",
    "umm", "uhh", "hmmm", "oh achha", "achha achha",
})


class FillerInjector(FrameProcessor):
    """Sits between the LLM and the TTS so a filler reaches the voice at once.

    FILLER BUG, 2026-09-23: the filler was queued at the head of the pipeline,
    so it waited behind the LLM, which handles one frame at a time and was busy
    generating the very reply the filler was meant to cover. The hum reached
    the TTS after the reply and played at the END of the turn ("it ended with
    hm"). Pushed from here, it skips the LLM and plays while the LLM thinks.
    """

    async def process_frame(self, frame, direction: FrameDirection):
        await super().process_frame(frame, direction)
        await self.push_frame(frame, direction)

    async def inject(self, frames) -> None:
        for frame in frames:
            await self.push_frame(frame)


# How the STT hears "Park+" on 8 kHz calls (call.log 2026-09-21..23). Fixed
# before the LLM so "पाकपस कैसी एप है?" is a question about Park+, not a word
# the model has never seen. Every Park+ domain shares the brand.
_STT_FIXES = re.compile(r"पाकपस|पाकपेस|पार्क\s*प्लेस|पाक\s*प्लस|\bpark\s*place\b", re.I)


class NoiseGate(FrameProcessor):
    #: Awaited after a transcript is dropped — run_bot uses it to re-answer a
    #: turn the noise interrupted. See _on_noise_drop there.
    on_drop = None

    """Drops transcripts that are the transcriber talking to itself.

    Sits between the STT and the user aggregator, so a dropped line never reaches
    the context and never earns a reply. The VAD above is the real fix and this is
    the net under it: VAD decides whether audio is speech, this decides whether a
    finished transcript is a turn.
    """

    def __init__(self):
        super().__init__()
        self.dropped: list[str] = []

    @staticmethod
    def _is_noise(text: str) -> bool:
        stripped = text.strip()
        if not stripped:
            return True
        bare = re.sub(r"[।.,!?…\"'`\-–—]+", "", stripped).strip().lower()
        bare = re.sub(r"\s+", " ", bare)
        words = bare.split()
        # Anything in Devanagari is the caller — EXCEPT a bare backchannel, which
        # is a noise, not a turn. Everything else in Hindi is left alone whatever
        # it says, which is what keeps one-word answers ("हाँ") working.
        if re.search(r"[\u0900-\u097F]", stripped):
            if bare in _HINDI_BACKCHANNELS:
                return True
            # Short vague room scraps ("देखने के लिए", "और भी") with no KYC
            # force. Real answers usually contain हाँ/नहीं/ठीक/कर/बता/… or are
            # longer turns.
            #
            # A caller STARTING to object or ask is short too. 2026-09-23: the
            # caller said "लेकिन ये" ("but this…"), it was dropped as noise, and
            # the bot sat silent until the 30s idle nudge. "But", question words,
            # addressing the bot and "wait" are someone talking TO the bot, so
            # they keep a short line. First-person words are left out: room
            # chatter uses them too.
            if len(words) <= 3 and not re.search(
                r"लेकिन|मगर|मतलब|क्या|कौन|क्यों|क्यूँ|कैसे|कहाँ|कहां|कब|कितन|"
                r"आप|सर|मैडम|जी|सुनि|सुनो|रुकि|रुको|एक\s*मिनट|वेट|"
                r"हाँ|हां|नहीं|नही|ठीक|हो\s*गया|कर|खोल|बता|हेलो|हैलो|बाय|"
                r"ऐप|फॉर्म|केवाईसी|आधार|पैन|पॉलिसी|टाइम|कॉल|पेज|बटन|"
                r"nominee|kyc|app|form|pan|aadhaar|aadhar|policy",
                bare,
                re.IGNORECASE,
            ):
                return True
            return False
        if bare in _NOISE_TRANSCRIPTS or bare in _ROMAN_BACKCHANNELS:
            return True
        # Latin / English office bleed with no romanised-Hindi / call markers
        # ("Marine Toy", "It would be there", placement chatter). Keep "yeah",
        # "nahi dikh raha", "ok" etc.
        if not re.search(
            r"\b(haan|hahn|nahi|nahin|theek|thik|gaya|ji|dikh|raha|batao|"
            r"bolo|app|kyc|ok|okay|yes|yeah|yep|hello|hi|bye|wait|later|"
            r"call|time|form|nominee|aadhaar|aadhar|pan)\b",
            bare,
        ):
            return True
        return False

    async def process_frame(self, frame, direction: FrameDirection):
        await super().process_frame(frame, direction)
        if isinstance(frame, TranscriptionFrame) and self._is_noise(frame.text):
            self.dropped.append(frame.text.strip())
            logger.info(f"NOISE  | dropped {frame.text.strip()!r}")
            if self.on_drop:
                await self.on_drop()
            return
        if isinstance(frame, TranscriptionFrame):
            frame.text = _STT_FIXES.sub("पार्क प्लस", frame.text)
        await self.push_frame(frame, direction)


# How fast Sarvam actually talks, for turning "seconds of bot audio played" into
# "how much of the reply the caller heard". Measured 2026-09-23 on bulbul:v3,
# shreya, pace 1.0, romanised Hinglish: 12.9 / 15.8 / 15.8 chars/s over three
# real bot lines. Retune if SARVAM_PACE or the voice changes.
SPEECH_CHARS_PER_SEC = float(os.getenv("SPEECH_CHARS_PER_SEC") or 14.5)


def split_heard(text: str, heard_secs: float) -> tuple[str, str]:
    """Split a reply into what the caller heard before barging in, and the rest.

    Sarvam sends no word timestamps, and its TTSTextFrames reach the context when
    a sentence is SENT for synthesis, not when it is played — so on barge-in the
    context held the whole reply, including sentences the caller never heard.
    Seconds of audio actually played are known, so cut at that many characters.
    ponytail: a speech-rate estimate, off by a word or two; word timestamps
    from the TTS would make it exact.
    """
    cut = int(max(heard_secs, 0.0) * SPEECH_CHARS_PER_SEC)
    if cut >= len(text):
        return text, ""
    # Back up to a word boundary so a half-word is not recorded as said.
    space = text.rfind(" ", 0, cut + 1)
    cut = space if space > 0 else 0
    return text[:cut].rstrip(), text[cut:].strip()


class CallLogObserver(BaseObserver):
    """Logs the call as a conversation: one CALLER line, one MONIKA line.

    Pipecat's own transcription observer logs at DEBUG, which is exactly the
    level being suppressed, and it only covers the caller's side. This watches
    both: the STT's final transcripts, and the sentences actually handed to the
    TTS — i.e. what the caller really heard, after the guardrails rewrote it.
    """

    # Two tiers, not one list, and NOT the same kind of sound:
    #
    # TIER1 is a non-lexical hum — "hmm"/"umm", not a word — for the FIRST
    # beat of dead air. Product ask 2026-09-22: "make sure there is someone
    # replying" without it reading as a canned button-press. Verified by
    # TTS -> STT round trip on 2026-09-22 before trusting Sarvam to pronounce
    # it as a hum rather than a word: "हम्म," and "उम्म," both came back as
    # short, genuine-sounding hums; "आहं," (an earlier candidate) came back
    # sounding like a surprised "aha", not someone thinking, so it is not here.
    #
    # TIER2 is real words — a hum held for 3+ seconds stops sounding like
    # someone thinking and starts sounding like the call is broken, so past
    # the first beat this switches to an actual acknowledgement that carries
    # meaning. TIER2 only fires if TIER1 already did and the reply is STILL
    # not back, so it scales with how overdue the turn actually is.
    # Fillers stay Devanagari under REPLY_SCRIPT=hinglish: they never enter the
    # LLM context (append_to_context=False), and the hums were verified by TTS
    # round trip in THIS spelling only.
    FILLER_TIER1 = ("हम्म,", "उम्म,", "हम्म...")
    # Tier 2 is real words, so it follows REPLY_SCRIPT like every other line;
    # in Devanagari under hinglish the guard flagged it as a wrong-script reply.
    FILLER_TIER2 = (
        ("Bas dekh rahi hoon sir,", "Ek second sir,", "Abhi batati hoon,")
        if HINGLISH_REPLIES
        else ("बस देख रही हूँ सर,", "एक सेकंड सर,", "अभी बताती हूँ,")
    )

    def __init__(
        self,
        guard=None,
        filler_delay_secs: float = 0.0,
        filler_delay2_secs: float = 0.0,
    ):
        super().__init__()
        self._said: list[str] = []
        # The whole call, redacted, for the Slack summary when it ends.
        self.transcript: list[str] = []
        # Awaited with each finished bot turn once it has been spoken — run_bot
        # uses it to hang up after the closing line and to alert on a handover.
        self.on_said = None
        # Latency filler, 2026-09-22, product ask: Gemini's own turn is
        # 1.5-2s, on top of ~1s of STT, so the caller sits in dead air for
        # nearly 3s before ANY sound. A short "हाँ सर," fired only once that
        # dead air has already run past filler_delay_secs — never before —
        # tells them the line is alive without adding to the wait: it plays
        # DURING time that was already going to be silent, not before it.
        #
        # 0 (default) = OFF. FILLER_DELAY_SECS in .env sets the tier-1
        # threshold; unset or 0 leaves this exactly as it was. filler_delay2
        # is ADDITIONAL seconds after tier 1 before tier 2 is even considered
        # — 0/unset means tier 2 never fires, so turning tier 1 on alone
        # keeps today's single-ack behaviour.
        self._filler_delay = filler_delay_secs
        self._filler_delay2 = filler_delay2_secs
        self._filler_task: asyncio.Task | None = None
        # Last phrase spoken, per tier, so back-to-back turns never repeat the
        # same ack — the thing that would make it sound like a canned button
        # rather than a person.
        self._last_filler: dict[int, str] = {}
        # A turn counter, not a boolean: if the caller barges in with a NEW
        # turn while a filler is still waiting to fire, the filler must know
        # it is now stale and stay silent for the turn that superseded it,
        # not speak over whatever the caller just said.
        self._turn_id = 0
        # Set once, right after PipelineWorker exists — see run_bot(). Frames
        # cannot be queued before that, and the filler task will not be
        # scheduled until this is set (filler_delay_secs stays 0 until then
        # would be wrong; instead _schedule_filler no-ops with no queue_frames).
        self._queue_frames = None
        # True from the moment the filler frame is actually queued until the
        # BotStartedSpeakingFrame it causes has been consumed. See that branch.
        self._filler_pending_frame = False
        # Wall-clock from the caller's final transcript to the bot's first
        # audio — the number that actually matters on a call, not a metrics
        # frame nobody reads. Set on every CALLER line, consumed and cleared
        # by the FIRST BotStartedSpeakingFrame after it, so a stray extra one
        # (barge-in resume, a reconnect) never logs a second, meaningless
        # latency for the same turn.
        self._turn_start: float | None = None
        # Silero's own acoustic stop (VAD_STOP_SECS, independent of AssemblyAI's
        # turn model) vs the STT's COMMITTED transcript. The gap between them is
        # AssemblyAI's own delay — its min_turn_silence/max_turn_silence wait
        # plus its network round trip — which _turn_start above cannot see,
        # because _turn_start is set only once the transcript already arrived.
        # Overwritten on every VAD stop, not just the first, so a mid-sentence
        # pause does not get mistaken for the real one; only the LAST stop
        # before the transcript commits is what AssemblyAI was actually timed
        # against.
        self._vad_stop: float | None = None
        # Seconds of bot audio actually played in the current assistant turn —
        # what split_heard() needs on a barge-in. Summed across speaking spans,
        # since Pipecat can emit stop/start between sentences.
        self._speak_t0: float | None = None
        self._spoken_secs = 0.0
        # FILLER BUG #2, 2026-09-23 (Park+ LLM): the reply text was already
        # streaming at 0.9s, the filler fired at 1.2s because audio had not
        # started yet, and the hum played AFTER the reply. A filler is only
        # for a turn whose reply has not started generating.
        self._reply_started = False
        # When the last barge-in happened, for re-answering a turn that a
        # dropped noise line interrupted — see run_bot's _on_noise_drop.
        self.last_interruption = 0.0
        # The same domain guard the TTS filter uses. The filter only ever sees what
        # the BOT says, so on its own it cannot know whether the caller ever named
        # a car — and "₹499 (Hyundai Creta के लिए)" for a caller who never said
        # Creta passes every content check. This is the only place both sides of
        # the conversation are visible, so this is where that gets recorded.
        self._guard = guard

    def attach_queue(self, queue_frames) -> None:
        """Give the observer a way to speak. Called once, after worker exists."""
        self._queue_frames = queue_frames

    def reset_heard(self) -> None:
        """A new assistant turn started: nothing of it has been heard yet."""
        self._spoken_secs = 0.0
        self._speak_t0 = time.monotonic() if self._speak_t0 is not None else None

    def heard_secs(self) -> float:
        """Seconds of the current assistant turn the caller has heard so far."""
        live = time.monotonic() - self._speak_t0 if self._speak_t0 is not None else 0.0
        return self._spoken_secs + live

    def _schedule_filler(self) -> None:
        """Arm the filler for THIS caller turn, replacing any earlier one."""
        self._turn_id += 1
        if self._filler_task is not None:
            self._filler_task.cancel()
            self._filler_task = None
        if self._filler_delay <= 0 or self._queue_frames is None:
            return
        self._filler_task = asyncio.create_task(self._fire_filler(self._turn_id))

    def _pick_filler(self, tier: int, phrases: tuple[str, ...]) -> str:
        """A phrase from this tier, never the one this tier said last time."""
        choices = [p for p in phrases if p != self._last_filler.get(tier)] or list(phrases)
        phrase = random.choice(choices)
        self._last_filler[tier] = phrase
        return phrase

    async def _speak_filler(self, phrase: str) -> None:
        # Sets the skip-flag right before queueing, not before sleeping — see
        # the BotStartedSpeakingFrame branch. Each filler utterance owns
        # exactly one BotStartedSpeakingFrame; this pairs the two correctly
        # even when tier 2 fires after tier 1 already did.
        self._filler_pending_frame = True
        await self._queue_frames([TTSSpeakFrame(phrase, append_to_context=False)])

    async def _fire_filler(self, turn_id: int) -> None:
        try:
            await asyncio.sleep(self._filler_delay)
        except asyncio.CancelledError:
            return
        # The real reply may have started, or a newer caller turn may have
        # superseded this one, in the time spent sleeping — both mean silence.
        if turn_id != self._turn_id or self._turn_start is None or self._reply_started:
            return
        await self._speak_filler(self._pick_filler(1, self.FILLER_TIER1))

        if self._filler_delay2 <= 0:
            return
        try:
            await asyncio.sleep(self._filler_delay2)
        except asyncio.CancelledError:
            return
        # Same staleness check, run again: tier 2 only speaks if the reply is
        # STILL not back after the extra wait — this is what makes it track
        # how overdue the turn actually is, not just a second fixed timer.
        if turn_id != self._turn_id or self._turn_start is None or self._reply_started:
            return
        await self._speak_filler(self._pick_filler(2, self.FILLER_TIER2))

    async def on_push_frame(self, data: FramePushed):
        frame = data.frame
        if isinstance(frame, TranscriptionFrame) and isinstance(data.source, STTService):
            if frame.text.strip():
                # redact(), not the raw transcript. On a KYC call the customer
                # reads their PAN and Aadhaar out loud, and call.log is an
                # unrestricted file — the insurance pack forbids raw identity
                # numbers landing in one. The bot still SEES the real value; only
                # the log is masked.
                logger.info(f"CALLER | {redact(frame.text.strip())}")
                now = time.monotonic()
                if self._vad_stop is not None:
                    logger.info(f"STT LAG | {now - self._vad_stop:.2f}s silence -> "
                                f"{type(data.source).__name__} committed the transcript")
                    self._vad_stop = None
                # The observer sees the transcript BEFORE NoiseGate drops it. A
                # dropped line is not a turn: starting the clock on it logged
                # "LATENCY 30.35s" for the idle nudge (2026-09-23), would fire a
                # filler hum at nobody, and fed the guard words the model never saw.
                if NoiseGate._is_noise(frame.text):
                    return
                self.transcript.append(f"Caller: {redact(frame.text.strip())}")
                self._turn_start = now
                self._reply_started = False
                self._schedule_filler()
                # Just hand it to the guard. This used to read
                # `self._guard.car_known` first — a car-spa-only attribute — and
                # crashed every insurance call with
                # "'KycGuard' object has no attribute 'car_known'". The observer
                # has no business knowing what a domain gates on; note_caller
                # returns True only on the turn something unlocks.
                if self._guard and self._guard.note_caller(frame.text):
                    logger.info("GUARD unlocked by the caller's answer")
        elif isinstance(frame, TTSTextFrame) and isinstance(data.source, TTSService):
            # The source check is not decoration. on_push_frame fires once per
            # PROCESSOR HOP, so one sentence travelling TTS -> transport.output
            # arrived here twice and every MONIKA line in the 21:55 log was
            # printed doubled ("दो मिनट बात कर लें? दो मिनट बात कर लें?"). The
            # caller heard it once; only the log was wrong.
            self._said.append(frame.text)
        elif isinstance(frame, VADUserStoppedSpeakingFrame):
            self._vad_stop = time.monotonic()
        elif isinstance(frame, LLMFullResponseStartFrame):
            self._reply_started = True
        elif isinstance(frame, InterruptionFrame):
            self.last_interruption = time.monotonic()
        elif isinstance(frame, MetricsFrame):
            # Where a slow LATENCY line went: LLM first token vs TTS first audio.
            # Pipecat logs these at DEBUG, which call.log suppresses. Source
            # check = log once, from the service that measured it, not per hop.
            for d in frame.data:
                if (isinstance(d, TTFBMetricsData) and d.value > 0
                        and d.processor == getattr(data.source, "name", None)):
                    logger.info(f"TTFB | {d.processor} {d.value:.2f}s")
        elif isinstance(frame, BotStartedSpeakingFrame):
            # Fires once per processor hop; only the first hop starts the span.
            if self._speak_t0 is None:
                self._speak_t0 = time.monotonic()
            # A pending VAD stop belongs to the turn that just ended. Left set,
            # it goes stale across the bot's own speech and the NEXT transcript
            # is measured against it: the 13:19 call logged "STT LAG | 14.89s"
            # for a transcript that arrived 0.2s after the caller spoke, because
            # the timestamp was from before a 7-second bot turn. Every STT LAG
            # over ~2s in that log is this, not the transcriber.
            self._vad_stop = None
            # The filler itself makes the pipeline speak, which means THIS event
            # fires once for "हाँ सर," starting and once more for the real reply
            # starting. Skip exactly the filler's own one — set right when the
            # filler frame is actually queued, in _fire_filler — so LATENCY still
            # measures caller -> REAL first audio, not caller -> filler.
            if self._filler_pending_frame:
                self._filler_pending_frame = False
                return
            if self._turn_start is not None:
                logger.info(
                    f"LATENCY | {time.monotonic() - self._turn_start:.2f}s caller -> first audio"
                )
                self._turn_start = None
        elif isinstance(frame, BotStoppedSpeakingFrame):
            if self._speak_t0 is not None:
                self._spoken_secs += time.monotonic() - self._speak_t0
                self._speak_t0 = None
            if self._said:
                # Joined on flush: the LLM streams a turn as several sentences, and
                # one log line per turn is what makes the transcript readable.
                said = " ".join(self._said).strip()
                self._said.clear()
                logger.info(f"MONIKA | {redact(said)}")
                self.transcript.append(f"Bot: {redact(said)}")
                if self.on_said:
                    await self.on_said(said)


def _message_role(message) -> str | None:
    """Role of a context message, whether it is a dict or an LLMSpecificMessage."""
    inner = getattr(message, "message", message)
    return inner.get("role") if isinstance(inner, dict) else None


def _message_text(message) -> str:
    """Text of a context message, whether it is a dict or an LLMSpecificMessage."""
    inner = getattr(message, "message", message)
    content = inner.get("content") if isinstance(inner, dict) else None
    return content if isinstance(content, str) else ""


def _estimate_tokens(text: str) -> int:
    """Rough token cost of a message, for the history budget.

    3.2 chars/token is the ratio measured against Groq's own prompt_tokens on this
    Devanagari/English mix (scratchpad/t_tokens.py). The 4 is the per-message
    role/scaffolding overhead, which matters when the history is many short turns.
    An estimate is fine here — it decides what to drop, never what to bill.
    """
    return int(len(text) / 3.2) + 4


def _reasoning_effort(model: str) -> str:
    """The lowest reasoning setting each model family will actually accept.

    Both families reason before answering and both need that turned down for a
    phone call, but they disagree on the word for it: Groq's gpt-oss rejects
    "none" outright — `400: reasoning_effort must be one of low, medium, or
    high` — and its minimum is "low". Hard-coding qwen's "none" meant that
    switching GROQ_MODEL to gpt-oss made every single turn fail with a 400, so
    the value has to follow the model rather than sit next to it.
    """
    return "low" if model.startswith("openai/gpt-oss") else "none"


